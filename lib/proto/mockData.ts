// DB category (lib/pipeline/collect.ts's extractCategory() output, or
// lib/sources/rss.ts's RSS_FEEDS category) → feedapp's Japanese taxonomy.
// This is the full set of values the pipeline can actually produce today.
const DB_CATEGORY_TO_TAXONOMY: Record<string, string> = {
  physics: "物理学",
  biology: "生物学",
  it_ai: "情報学",
  medicine: "医学",
  astronomy: "天文学",
  chemistry: "化学",
  environment: "環境科学",
  mathematics: "数学",
  other: "その他",
  general: "その他",
};

// The pipeline has no distinct "neuroscience" category (see comment on
// CATEGORIES above), but plenty of biology/medicine papers ARE neuroscience
// (bioRxiv's neuroscience/animal-behavior-and-cognition feeds land in
// "biology"; medRxiv's neurology feed lands in "medicine" — see
// BIORXIV_CATEGORY_QUERIES in lib/sources/biorxiv.ts). Rather than leaving
// 神経科学 permanently empty or fabricating a classification with an extra
// LLM call, reclassify biology/medicine items whose title or summary text
// mentions brain/neuro terms — a simple, honest, deterministic keyword check
// over real content already in hand.
const NEURO_KEYWORDS = [
  "脳", "神経", "ニューロン", "シナプス", "大脳", "小脳", "海馬", "脳幹",
  "皮質", "脳波", "認知科学", "意識", "睡眠", "麻酔",
  "brain", "neuro", "cortex", "synap", "cogniti", "conscious",
];

/**
 * Maps a raw DB category value (English, from collect.ts / rss.ts) to one of
 * feedapp's Japanese CATEGORIES. `text` (title + summary) is optional context
 * used only to reclassify biology/medicine items into 神経科学.
 */
export function mapDbCategoryToTaxonomy(dbCategory: string | null | undefined, text?: string): string {
  const key = (dbCategory ?? "").toLowerCase().trim();
  const base = DB_CATEGORY_TO_TAXONOMY[key] ?? "その他";
  if ((base === "生物学" || base === "医学") && text) {
    const lower = text.toLowerCase();
    if (NEURO_KEYWORDS.some((kw) => lower.includes(kw))) return "神経科学";
  }
  return base;
}

